"""
Equivalence check for the nis_util.py refactor (TODO #5).

Compares, byte for byte, the .mac macro text generated by the OLD
nis_util (frozen snapshot next to this file: nis_util_old.py) and the
NEW one (nis_util.py at the repo root) for every wrapper, using
deterministic fake temp-file names and a no-op fake `subprocess.call`.
Run it any time nis_util.py changes: a macro body may only differ from
the snapshot if the change is deliberate (in that case update the
snapshot with the new body).

Also:
  - round-trip tests of the new code with a fake nis_ar that fills the
    .ini result file (verifies placeholder substitution + parsing),
  - the two intentional behaviour fixes (get_position without a piezo,
    set_position pos_piezo),
  - PermissionError tolerance when cleaning up locked .mac files.
"""
