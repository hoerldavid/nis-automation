NIS = r'C:\fake\nis_ar.exe'
TMPDIR = tempfile.gettempdir()


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


old = load_module(os.path.join(HERE, 'nis_util_old.py'), 'nis_util_old')
new = load_module(os.path.join(ROOT, 'nis_util.py'), 'nis_util_new')

# ------------------------------------------------------------------
# fakes

CALLS = []
MAC_BODIES = []


class FakeNTF:
    """deterministic NamedTemporaryFile stand-in (same names every run)"""
    counter = 0

    def __init__(self, suffix='.mac', delete=False):
        FakeNTF.counter += 1
        self.name = os.path.join(TMPDIR, 'nistest_%d%s' % (FakeNTF.counter, suffix))
        self._f = open(self.name, 'wb')

    def writelines(self, lines):
        self._f.writelines(lines)

    def close(self):
        if not self._f.closed:
            self._f.close()


def _clean_fakes():
    global FAKE_INI
    FAKE_INI = None
    FakeNTF.counter = 0
    CALLS.clear()
    MAC_BODIES.clear()
    for f in os.listdir(TMPDIR):
        if f.startswith('nistest_'):
            os.remove(os.path.join(TMPDIR, f))


FAKE_INI = None  # if set, the fake nis_ar writes this into the .ini


def fake_call(cmdline):
    CALLS.append(cmdline)
    mac = cmdline.split()[-1].strip('"')
    MAC_BODIES.append(open(mac, 'rb').read())  # snapshot: nis_ar owns the file now
    if FAKE_INI is not None:
        body = MAC_BODIES[-1].decode('utf-8')
        m = re.search(r'Int_SetKey(?:String|Value)\("([^"]+)"', body)
        assert m, 'no ini reference found in macro: %s' % body
        with open(m.group(1), 'w', encoding='utf-8') as fh:
            fh.write(FAKE_INI)
    return 0


def run_capture(mod, fn, clean=True):
    """run fn (from module mod) with fakes; return (mac_body_bytes, result_or_exc)"""
    if clean:
        _clean_fakes()
    mod.NamedTemporaryFile = FakeNTF
    real_call = subprocess.call
    subprocess.call = fake_call
    try:
        try:
            result = fn(mod)
        except Exception as e:  # expected for ini fns with an empty ini
            result = e
    finally:
        subprocess.call = real_call
    assert len(CALLS) == 1, 'expected exactly one nis_ar call, got %r' % CALLS
    body = MAC_BODIES[-1]
    mac = CALLS[0].split()[-1].strip('"')
    # cleanup happened inside the wrapper
    assert not os.path.exists(mac), 'temp .mac not cleaned up: %s' % mac
    return body, result


def run_roundtrip(mod, fn, ini_content):
    """run fn with the fake nis_ar writing `ini_content` into the .ini"""
    global FAKE_INI
    _clean_fakes()          # resets FAKE_INI first
    FAKE_INI = ini_content
    body, result = run_capture(mod, fn, clean=False)
    assert not isinstance(result, Exception), 'unexpected exception: %r' % result
    return body, result


